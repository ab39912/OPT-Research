#!/usr/bin/env python3
"""
cross_dataset.py  (Milestone B — cross-platform comparison)
-----------------------------------------------------------
Reads two or more CSV datasets, identifies which columns they share, and
compares summary statistics for those shared columns side by side. Writes a
Markdown report (default: CROSS_DATASET.md) and prints a summary to stdout.

This is deliberately schema-agnostic: it works on the Facebook Ads, Facebook
Posts, and Twitter/X Posts files without any per-dataset hardcoding, and would
work on an unrelated set of CSVs too. All type/null/cleaning decisions come from
the shared datakit module, so the numbers here are consistent with what the
per-dataset scripts report.

Usage:
    python cross_dataset.py ads.csv posts.csv tweets.csv
    python cross_dataset.py --out CROSS_DATASET.md file1.csv file2.csv [...]
    # optional friendly labels, one per file, in order:
    python cross_dataset.py --labels ads posts tweets a.csv b.csv c.csv
"""

import argparse
import csv
import math
import os
import sys
from collections import Counter

import datakit as dk

csv.field_size_limit(min(sys.maxsize, 2**31 - 1))


# --------------------------------------------------------------------------- #
# Loading + per-dataset summary (pure stdlib, so no third-party dependency)
# --------------------------------------------------------------------------- #
def load_columns(path):
    with open(path, newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        header = next(reader)
        cols = {h: [] for h in header}
        for row in reader:
            for i, h in enumerate(header):
                cols[h].append(row[i] if i < len(row) else None)
    return header, cols


def numeric_summary(values):
    nums = [float(v) for v in values
            if not dk.is_missing(v) and dk.try_float(v)]
    n = len(nums)
    if n == 0:
        return None
    mean = math.fsum(nums) / n
    if n > 1:
        std = math.sqrt(math.fsum((x - mean) ** 2 for x in nums) / (n - 1))
    else:
        std = 0.0
    ordered = sorted(nums)
    mid = n // 2
    median = ordered[mid] if n % 2 else (ordered[mid - 1] + ordered[mid]) / 2
    return dict(count=n, mean=mean, std=std, min=ordered[0],
                max=ordered[-1], median=median)


def categorical_summary(values):
    present = [str(v).strip() for v in values if not dk.is_missing(v)]
    c = Counter(present)
    mode = c.most_common(1)
    return dict(count=len(present), unique=len(c),
                mode=(mode[0][0] if mode else None),
                mode_freq=(mode[0][1] if mode else 0))


def summarize_dataset(path):
    header, cols = load_columns(path)
    kinds = {h: dk.classify_column(cols[h]) for h in header}
    # Add derived clean companions so shared *derived* metrics can be compared
    # too (e.g. spend__midpoint if a dataset has a spend range column).
    for new_col, (src, tf) in dk.derived_columns(kinds).items():
        fn = dk.TRANSFORMS[tf]
        cols[new_col] = [fn(v) if not dk.is_missing(v) else None for v in cols[src]]
        header.append(new_col)
        kinds[new_col] = "float" if tf == "range_midpoint" else "integer"

    n_rows = len(next(iter(cols.values()))) if cols else 0
    summary = {"__rows__": n_rows, "__cols__": header, "__kinds__": kinds,
               "columns": {}}
    for h in header:
        if kinds[h] in ("integer", "float"):
            summary["columns"][h] = ("numeric", numeric_summary(cols[h]))
        elif kinds[h] == "empty":
            summary["columns"][h] = ("empty", None)
        else:
            summary["columns"][h] = ("categorical", categorical_summary(cols[h]))
    return summary


# --------------------------------------------------------------------------- #
# Report building
# --------------------------------------------------------------------------- #
def build_report(paths, labels):
    summaries = {}
    for path, label in zip(paths, labels):
        print(f"[reading] {label}: {path}")
        summaries[label] = summarize_dataset(path)

    col_sets = {lbl: set(s["__cols__"]) for lbl, s in summaries.items()}
    shared = set.intersection(*col_sets.values()) if col_sets else set()
    # Keep a stable, readable order using the first dataset's column order.
    first_order = summaries[labels[0]]["__cols__"]
    shared_ordered = [c for c in first_order if c in shared]

    lines = []
    lines.append("# Cross-Dataset Comparison\n")
    lines.append("Generated by `cross_dataset.py`. All type, null, and cleaning "
                 "decisions come from the shared `datakit` module, so these "
                 "figures are consistent with the per-dataset scripts.\n")

    # Overview table.
    lines.append("## Datasets\n")
    lines.append("| Dataset | Rows | Columns |")
    lines.append("|---|---:|---:|")
    for lbl in labels:
        s = summaries[lbl]
        lines.append(f"| {lbl} | {s['__rows__']:,} | {len(s['__cols__']):,} |")
    lines.append("")

    # Shared vs unique columns.
    lines.append("## Shared and platform-specific columns\n")
    lines.append(f"**Shared by all {len(labels)} datasets ({len(shared_ordered)}):** "
                 + (", ".join(f"`{c}`" for c in shared_ordered) or "_none_") + "\n")
    for lbl in labels:
        unique = sorted(col_sets[lbl] - shared)
        lines.append(f"**Only in {lbl} ({len(unique)}):** "
                     + (", ".join(f"`{c}`" for c in unique) or "_none_") + "\n")

    # Per shared column, compare across datasets.
    lines.append("## Shared-column statistics across datasets\n")
    if not shared_ordered:
        lines.append("_No columns are common to all datasets, so there is "
                     "nothing to compare directly. Consider normalizing column "
                     "names (e.g. mapping `account_id` <-> `page_id`) first._\n")
    for col in shared_ordered:
        # Determine a common kind: numeric only if numeric in every dataset.
        kinds_here = [summaries[lbl]["columns"][col][0] for lbl in labels]
        lines.append(f"### `{col}`\n")
        if all(k == "numeric" for k in kinds_here):
            lines.append("| Dataset | count | mean | median | std | min | max |")
            lines.append("|---|---:|---:|---:|---:|---:|---:|")
            for lbl in labels:
                st = summaries[lbl]["columns"][col][1]
                if st is None:
                    lines.append(f"| {lbl} | 0 | — | — | — | — | — |")
                else:
                    lines.append(
                        f"| {lbl} | {st['count']:,} | {st['mean']:,.2f} | "
                        f"{st['median']:,.2f} | {st['std']:,.2f} | "
                        f"{st['min']:,.2f} | {st['max']:,.2f} |")
        else:
            lines.append("| Dataset | kind | non-null | unique | mode (freq) |")
            lines.append("|---|---|---:|---:|---|")
            for lbl in labels:
                kind, st = summaries[lbl]["columns"][col]
                if kind == "numeric":
                    lines.append(f"| {lbl} | numeric | {st['count']:,} | — | — |")
                elif kind == "empty" or st is None:
                    lines.append(f"| {lbl} | {kind} | 0 | 0 | — |")
                else:
                    mode = str(st["mode"])
                    mode = (mode[:30] + "…") if len(mode) > 31 else mode
                    lines.append(f"| {lbl} | {kind} | {st['count']:,} | "
                                 f"{st['unique']:,} | {mode} ({st['mode_freq']:,}) |")
        lines.append("")

    return "\n".join(lines), shared_ordered


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+", help="Two or more CSV paths.")
    ap.add_argument("--labels", nargs="+", default=None,
                    help="Friendly labels, one per file, in the same order.")
    ap.add_argument("--out", default="CROSS_DATASET.md")
    args = ap.parse_args()

    if len(args.files) < 2:
        sys.exit("Provide at least two CSV files to compare.")
    for f in args.files:
        if not os.path.exists(f):
            sys.exit(f"ERROR: file not found: {f}")

    if args.labels and len(args.labels) != len(args.files):
        sys.exit("Number of --labels must match number of files.")
    labels = args.labels or [os.path.splitext(os.path.basename(f))[0]
                             for f in args.files]

    report, shared = build_report(args.files, labels)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(report)
    print(f"\nShared columns across all datasets: {len(shared)}")
    print(f"Wrote report -> {args.out}")


if __name__ == "__main__":
    main()
